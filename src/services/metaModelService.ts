// Local storage key for persistency
const STORAGE_KEY = 'deepdoc_partner_config';

export function getSavedPartnerConfig(): PartnerConfig {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) return { ...DEFAULT_PARTNER_CONFIG, ...JSON.parse(raw) };
  } catch (e) {
    // ignore
  }
  return DEFAULT_PARTNER_CONFIG;
}

export function savePartnerConfig(config: PartnerConfig) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(config));
  } catch (e) {
    // ignore
  }
}

