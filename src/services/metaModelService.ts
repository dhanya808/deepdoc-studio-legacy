  /**
   * Muse Spark: Table Extraction & Conversion
   */
  public async extractTableToFormats(segment: DocumentSegment): Promise<{
    csv: string;
    json: string;
    sql: string;
    pandasCode: string;
  }> {
    if (!segment.tableData) {
      throw new Error('Segment contains no tabular data.');
    }

    const { headers, rows } = segment.tableData;

    // CSV format
    const csvLines = [
      headers.join(','),
      ...rows.map((row) => row.map((cell) => `"${cell}"`).join(',')),
    ];
    const csv = csvLines.join('\n');

    // JSON format
    const jsonData = rows.map((row) => {
      const obj: Record<string, string | number> = {};
      headers.forEach((header, idx) => {
        obj[header] = row[idx];
      });
      return obj;
    });
    const json = JSON.stringify(jsonData, null, 2);

    // SQL create and insert
    const tableName = segment.label.toLowerCase().replace(/[^a-z0-9]/g, '_').slice(0, 30);
    const sqlColumns = headers.map((h) => `  \`${h.replace(/[^a-zA-Z0-9_]/g, '_')}\` VARCHAR(255)`).join(',\n');
    const sql = `-- Generated by Meta Muse Spark Table Synthesizer\nCREATE TABLE ${tableName} (\n${sqlColumns}\n);\n\n-- Batch insert ready\nINSERT INTO ${tableName} VALUES\n` +
      rows.map((r) => `  (${r.map((v) => `'${v}'`).join(', ')})`).join(',\n') + ';';

    // Pandas Code
    const pandasCode = `# Generated by Meta Muse Spark Python Code Generator
import pandas as pd
import io

csv_data = """${csv}"""

df = pd.read_csv(io.StringIO(csv_data))
print("Loaded Table Shape:", df.shape)
print(df.head())

# Compute quick aggregates
print("\\nDescriptive Statistics:")
print(df.describe(include='all'))
`;

    return { csv, json, sql, pandasCode };
  }

